"""Regenerate the Supabase setup script from the backend table definitions."""

from pathlib import Path

from ..content_store import SETTINGS, TABLES, fields, table_schema
from ..db import SCHEMA

HEADER = """-- Generated by python -m backend.supabase.generate_setup.
-- Re-running preserves existing records.
BEGIN;
SELECT pg_advisory_xact_lock(687445720301);
CREATE SCHEMA IF NOT EXISTS dhog;
REVOKE ALL ON SCHEMA dhog FROM PUBLIC;
SET LOCAL search_path TO dhog, pg_catalog;

DO $$
BEGIN
    IF to_regclass('dhog.staff') IS NOT NULL THEN
        IF to_regclass('dhog.admin') IS NOT NULL THEN
            RAISE EXCEPTION 'Both dhog.staff and dhog.admin exist';
        END IF;
        ALTER TABLE dhog.staff RENAME TO admin;
    END IF;
END;
$$;
"""

MIGRATION = """
DO $$
DECLARE
    snapshot jsonb;
    snapshot_version integer;
BEGIN
    IF to_regclass('dhog.site') IS NULL THEN
        RETURN;
    END IF;
    IF to_regclass('dhog.site_legacy_backup') IS NOT NULL
       OR EXISTS (SELECT 1 FROM site_state WHERE id=1) THEN
        RAISE EXCEPTION 'Both legacy and normalized site records exist. Review before migrating.';
    END IF;

    SELECT data::jsonb, version INTO snapshot, snapshot_version FROM dhog.site WHERE id=1 FOR UPDATE;
    IF FOUND THEN
        IF jsonb_typeof(snapshot) <> 'object' OR EXISTS (
            SELECT 1 FROM jsonb_object_keys(snapshot) AS key(name)
            WHERE name NOT IN ({known})
        ) THEN
            RAISE EXCEPTION 'The old site contains unrecognized data';
        END IF;
{migrate}
        INSERT INTO site_state (id, version, last_backup_date)
        VALUES (1, snapshot_version + 1, COALESCE(snapshot->>'lastBackupDate', ''));
    END IF;

    ALTER TABLE dhog.site RENAME TO site_legacy_backup;
END;
$$;

COMMIT;
"""


def postgres_column(key, kind):
    value = f"record->'{key}'"
    text = f"(record->>'{key}')"
    actual = f"jsonb_typeof({value})"
    if kind == "json":
        return f"{actual} <> 'null'", f"({value})::text"
    if kind == "bool":
        return f"{actual} = 'boolean'", f"({text}::boolean)::integer"
    if kind == "int":
        condition = f"CASE WHEN {actual} = 'number' AND {text} ~ '^-?[0-9]+$' THEN {text}::numeric BETWEEN -9223372036854775808 AND 9223372036854775807 ELSE false END"
        return condition, f"{text}::bigint"
    if kind == "number":
        return f"{actual} = 'number'", f"{text}::double precision"
    return f"{actual} = 'string'", text


def migration_insert(key, table, spec):
    if key in SETTINGS:
        columns, values, excluded = ["id"], ["1"], "record"
        source = f"(SELECT snapshot->'{key}' AS record WHERE snapshot ? '{key}') AS settings"
        expected = f"CASE WHEN snapshot ? '{key}' THEN 1 ELSE 0 END"
    else:
        columns, values = ["sort_order"], ["ordinal - 1"]
        excluded = "record"
        if key != "recurringPrograms":
            columns.append("id")
            values.append("record->>'id'")
            excluded += " - 'id'"
        items = f"COALESCE(snapshot->'{key}', '[]'::jsonb)"
        source = f"jsonb_array_elements({items}) WITH ORDINALITY AS rows(record, ordinal)"
        expected = f"jsonb_array_length({items})"
    typed_keys = []
    for field, column, kind in fields(spec):
        condition, conversion = postgres_column(field, kind)
        columns.append(column)
        values.append(f"CASE WHEN {condition} THEN {conversion} END")
        typed_keys.append(f"CASE WHEN {condition} THEN '{field}' END")
    columns.append("extra_fields")
    values.append(f"({excluded} - array_remove(ARRAY[{', '.join(typed_keys)}]::text[], NULL))::text")
    return (
        f"        INSERT INTO {table} ({', '.join(columns)})\n"
        f"        SELECT {', '.join(values)}\n"
        f"        FROM {source};\n"
        f"        IF (SELECT count(*) FROM {table}) <> ({expected}) THEN\n"
        f"            RAISE EXCEPTION 'Row count mismatch for {table}';\n"
        "        END IF;"
    )


def generate():
    known = ", ".join(f"'{key}'" for key in (*TABLES, "lastBackupDate"))
    migrate = "\n\n".join(migration_insert(key, table, spec) for key, (table, spec) in TABLES.items())
    structure = ";\n\n".join(table_schema()) + ";"
    return (HEADER + "\n" + SCHEMA.strip() + "\n\n" + structure).replace("LONGTEXT", "TEXT") + (
        "\n\nCREATE INDEX IF NOT EXISTS delivery_state ON deliveries(state, campaign_id);\n"
        + MIGRATION.format(known=known, migrate=migrate)
    )


if __name__ == "__main__":
    Path(__file__).with_name("setup.sql").write_text(generate(), encoding="utf-8")
